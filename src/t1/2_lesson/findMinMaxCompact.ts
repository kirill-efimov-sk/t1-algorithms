const findMinMaxCompact = (arr: Array<number>) => {
    const start = performance.now();

    const n = arr.length;
    if (n === 0) return { min: undefined, max: undefined };
    if (n === 1) return { min: arr[0], max: arr[0] };

    let min: number, max: number, i: number;

    // Инициализация: если массив нечетный, берем первый элемент как min и max
    if (n % 2 !== 0) {
        min = max = arr[0];
        i = 1;
    } else {
        // Если четный — сравниваем первые два
        if (arr[0] < arr[1]) {
            min = arr[0];
            max = arr[1];
        } else {
            min = arr[1];
            max = arr[0];
        }
        i = 2;
    }

    // Проходим по остальным элементам ПАРАМИ (на каждую пару 3 сравнения)
    for (i; i < n; i += 2) {
        const a = arr[i];
        const b = arr[i + 1];
        //1 cравнение
        if (a < b) {
            // 2 cравнение
            if (a < min) min = a;
            // 3 cравнение
            if (b > max) max = b;
        } else {
            // 2 cравнение
            if (b < min) min = b;
            // 3 cравнение
            if (a > max) max = a;
        }
    }

    const end = performance.now();
    const duration = end - start;
    console.log(`Time taken: ${duration.toFixed(4)} ms`);
    console.log(`Array length: ${n}`);

    return { min, max };
};

